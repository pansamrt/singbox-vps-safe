#!/usr/bin/env python3
"""Combine *reviewed* singbox-vps-safe single-inbound JSON configs offline.

GPL-3.0-only. Does not access the network or change system settings.
Only JSON files generated by scripts/generate_config.py are intended as inputs.
"""
import argparse
import ipaddress
import json
import os
from pathlib import Path
import stat
import sys

import generate_config

ALLOWED = {"vless", "hysteria2", "tuic", "anytls"}
UDP = {"hysteria2", "tuic"}
EXPECTED_CLIENT = {"vless": "vless-reality", "hysteria2": "hysteria2",
                   "tuic": "tuic", "anytls": "anytls"}
MAX_INPUTS = 8
MAX_JSON_BYTES = 512 * 1024


def load_private_json(path: Path) -> dict:
    info = path.lstat()
    if not stat.S_ISREG(info.st_mode) or info.st_mode & 0o077:
        raise ValueError(f"Input must be a private regular file (mode 0600): {path}")
    if info.st_size > MAX_JSON_BYTES:
        raise ValueError("Input exceeds size limit")
    with path.open("r", encoding="utf8") as f:
        payload = json.load(f)
    if not isinstance(payload, dict):
        raise ValueError("Expected JSON object")
    return payload


def check_fragment(config: dict, client: dict) -> tuple[dict, dict]:
    if set(config) != {"log", "inbounds", "outbounds", "route"}:
        raise ValueError("Unexpected top-level fields; combine only generated single-inbound files")
    if config["log"] != {"level": "warn"}:
        raise ValueError("Unexpected logging configuration")
    if config["outbounds"] != [{"type": "direct", "tag": "direct"}] or config["route"] != {"final": "direct"}:
        raise ValueError("Unsupported routing/outbound; cannot combine")
    inbounds = config["inbounds"]
    if not isinstance(inbounds, list) or len(inbounds) != 1 or not isinstance(inbounds[0], dict):
        raise ValueError("One inbound per fragment required")
    inbound = inbounds[0]
    protocol = inbound.get("type")
    if protocol not in ALLOWED:
        raise ValueError("Only the four reviewed protocol types are allowed")
    tag = inbound.get("tag")
    if not isinstance(tag, str) or tag != EXPECTED_CLIENT[protocol] + "-in":
        raise ValueError("Unexpected inbound tag")
    listen = inbound.get("listen")
    try:
        ipaddress.ip_address(listen)
    except (TypeError, ValueError) as exc:
        raise ValueError("Invalid listen IP address") from exc
    port = inbound.get("listen_port")
    if type(port) is not int or not 1 <= port <= 65535:
        raise ValueError("Invalid inbound port")
    tls = inbound.get("tls")
    if not isinstance(tls, dict) or tls.get("enabled") is not True:
        raise ValueError("TLS must be enabled")
    if any(key in tls for key in ("insecure", "skip_cert_verify", "certificate", "key")):
        raise ValueError("Unexpected TLS override")
    if protocol == "vless":
        if "reality" not in tls or tls["reality"].get("enabled") is not True:
            raise ValueError("Only VLESS-Reality is accepted")
    else:
        if "reality" in tls:
            raise ValueError("Unexpected Reality fields")
        for key in ("certificate_path", "key_path", "server_name"):
            if not tls.get(key) or not isinstance(tls[key], str):
                raise ValueError("Missing TLS certificate/path/hostname")
        generate_config.valid_domain(tls["server_name"])
        generate_config.valid_cert_path(tls["certificate_path"])
        generate_config.valid_cert_path(tls["key_path"])
    if not isinstance(client, dict) or client.get("protocol") != EXPECTED_CLIENT[protocol]:
        raise ValueError("Client sidecar protocol mismatch")
    if client.get("listen_port") != port:
        raise ValueError("Client sidecar port mismatch")
    # Only pass through the single reviewed inbound; do not import unrelated routing.
    return inbound, client


def combine(inputs: list[Path]) -> tuple[dict, dict]:
    if not 1 <= len(inputs) <= MAX_INPUTS:
        raise ValueError(f"Expected between 1 and {MAX_INPUTS} inputs")
    seen_tags = set()
    seen_sockets = set()
    inbounds = []
    clients = []
    for file in inputs:
        if file.name.endswith(".client.json"):
            raise ValueError("Pass only server JSON paths, not .client.json paths")
        config = load_private_json(file)
        sidecar = load_private_json(file.with_name(file.name + ".client.json"))
        inbound, client = check_fragment(config, sidecar)
        tag = inbound["tag"]
        if tag in seen_tags:
            raise ValueError(f"Duplicate inbound tag: {tag}")
        seen_tags.add(tag)
        transport = "udp" if inbound["type"] in UDP else "tcp"
        # Conservative: duplicate transport/port is forbidden regardless of IP address.
        binding = (transport, inbound["listen_port"])
        if binding in seen_sockets:
            raise ValueError(f"Potential {transport.upper()} listen port conflict: {binding[1]}")
        seen_sockets.add(binding)
        inbounds.append(inbound)
        clients.append(client)
    config = {
        "log": {"level": "warn"}, "inbounds": inbounds,
        "outbounds": [{"type": "direct", "tag": "direct"}], "route": {"final": "direct"}
    }
    return config, {"clients": clients}


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--output", required=True, help="New private combined JSON path")
    p.add_argument("fragments", nargs="+", help="Generated single-inbound server JSON paths")
    args = p.parse_args(argv)
    output = Path(args.output)
    sidecar = output.with_name(output.name + ".client.json")
    if output.exists() or output.is_symlink() or sidecar.exists() or sidecar.is_symlink():
        p.error("Output files must not exist; refusing overwrite")
    if not output.parent.is_dir() or output.parent.is_symlink():
        p.error("Output directory missing or symlinked")
    os.umask(0o077)
    created = []
    try:
        config, clients = combine([Path(x) for x in args.fragments])
        try:
            generate_config.private_write(output, config)
            created.append(output)
            generate_config.private_write(sidecar, clients)
            created.append(sidecar)
        except BaseException:
            for path in created:
                path.unlink(missing_ok=True)
            raise
    except (ValueError, OSError, json.JSONDecodeError) as exc:
        p.error(str(exc))
    print(f"Created {len(config['inbounds'])} inbound(s) in private config and sidecar:")
    print(output)
    print(sidecar)
    print("Review both files and run sing-box check. No secrets were displayed.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
